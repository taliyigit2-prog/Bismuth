#!/usr/bin/env node
// node scripts/camera-lock.mjs            (needs `uv` on PATH: `pip install uv`; network; run by the packager, never by the app)
//
// Writes the hash-locked requirement files of the camera add-on (P20ffix, supply chain):
//   otel-kamera/requirements-bundle.lock   every library of the add-on, universal (Windows + macOS), sha256 of every file
//   otel-kamera/requirements-build.lock    the tools that compile insightface (setuptools, Cython, numpy)
//   otel-kamera/requirements-insightface.lock   insightface 0.7.3 (source archive, sha256; built on the packaging computer)
// scripts/camera-bundle.mjs installs them with `pip install --require-hashes --no-deps --only-binary=:all:` from ONE index
// (PyPI): PyPI's Windows torch wheel is the CPU build (same size as download.pytorch.org/whl/cpu), so no second index and
// no "extra index" mix-up. Pins come from otel-kamera/requirements.txt (the single place the versions are chosen);
// libraries that only the Linux GPU build of torch needs (nvidia-*, cuda-*, triton) are dropped.
// Re-run after changing a pin, then commit the three .lock files.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const kamera = join(root, 'otel-kamera')
const INDEX = 'https://pypi.org/simple'

const lines = (file) =>
  readFileSync(join(kamera, file), 'utf8')
    .split(/\r?\n/)
    .map((l) => l.split('#')[0].trim())
    .filter(Boolean)

const direct = lines('requirements.txt')
const bundle = lines('requirements-bundle.txt') // torch, torchvision
const insightface = direct.find((l) => /^insightface==/.test(l))
if (!insightface) throw new Error('requirements.txt has no insightface pin')

// What `from insightface.app import FaceAnalysis` really imports (measured with 0.7.3: onnx, albumentations, scikit-image,
// matplotlib, scipy, requests, tqdm, Pillow). insightface is installed without dependencies, so they are named here.
const INSIGHTFACE_IMPORTS = [
  'onnx',
  'albumentations',
  'scikit-image',
  'matplotlib',
  'scipy',
  'requests',
  'tqdm',
  'Pillow'
]
// `ultralytics` lists the Ultralytics Platform SDK (and through it httpx), but only imports it when `ultralytics.Platform`
// is touched; the add-on never does, so neither package is shipped (no API client, no telemetry; model_loader.py also sets
// YOLO_OFFLINE). `opencv-python` is replaced by the headless build pinned in requirements.txt.
const DROP = new Set(['httpx', 'httpcore', 'ultralytics-platform', 'opencv-python'])

const work = mkdtempSync(join(tmpdir(), 'camera-lock-'))
const uv = (input, out, extra = []) => {
  const file = join(work, `${out}.in`)
  writeFileSync(file, input.join('\n') + '\n')
  const result = join(work, `${out}.txt`)
  execFileSync(
    'uv',
    [
      'pip',
      'compile',
      file,
      '--universal',
      '--python-version',
      '3.12',
      '--generate-hashes',
      '--index-url',
      INDEX,
      '--no-header',
      '--no-annotate',
      '-o',
      result,
      ...extra
    ],
    { stdio: ['ignore', 'ignore', 'inherit'] }
  )
  return readFileSync(result, 'utf8')
}

/** Splits uv's output into [name, marker, text] blocks, dropping what the add-on does not ship. */
function filter(text) {
  const blocks = []
  for (const line of text.split(/\r?\n/)) {
    if (/^[A-Za-z0-9_.-]+==/.test(line)) blocks.push([line])
    else if (/^\s/.test(line) && blocks.length) blocks.at(-1).push(line)
  }
  return blocks.filter((b) => {
    const name = b[0].split('==')[0].toLowerCase()
    const marker = b[0].includes(';') ? b[0].split(';')[1] : ''
    if (DROP.has(name)) return false
    // Linux-only (the CUDA stack of the Linux torch wheel): the add-on is built for Windows and macOS.
    return !(marker && !/win32|darwin|Windows|Darwin/.test(marker))
  })
}

const header = (what, how) =>
  `# ${what}\n# Generated by scripts/camera-lock.mjs (uv pip compile --universal --generate-hashes, ${INDEX}); do not edit by hand.\n` +
  `# Installed by scripts/camera-bundle.mjs with: ${how}\n`

const ONLY_WHEELS = 'pip install --require-hashes --no-deps --only-binary=:all: -r <this file>'

const write = (name, what, how, blocks) =>
  writeFileSync(join(kamera, name), header(what, how) + blocks.map((b) => b.join('\n')).join('\n') + '\n')

try {
  const main = filter(
    uv([...direct.filter((l) => l !== insightface), ...bundle, ...INSIGHTFACE_IMPORTS], 'bundle')
  )
  write(
    'requirements-bundle.lock',
    'Camera add-on libraries (Windows + macOS, Python 3.12)',
    ONLY_WHEELS,
    main
  )

  const build = filter(
    uv(['setuptools', 'cython', `numpy==${direct.find((l) => /^numpy==/.test(l))?.split('==')[1]}`], 'build')
  )
  write(
    'requirements-build.lock',
    'Tools that compile insightface on the packaging computer',
    ONLY_WHEELS,
    build
  )

  // insightface itself: only its source archive (no wheel exists), pinned by hash.
  const [name, version] = insightface.split('==')
  const meta = JSON.parse(
    execFileSync(
      'curl',
      ['-fsS', '--proto', '=https', '--max-time', '60', `https://pypi.org/pypi/${name}/${version}/json`],
      {
        encoding: 'utf8'
      }
    )
  )
  const sdist = meta.urls.find((u) => u.packagetype === 'sdist')
  if (!sdist) throw new Error('no source archive for insightface')
  writeFileSync(
    join(kamera, 'requirements-insightface.lock'),
    header(
      'insightface (source archive; compiled once on the packaging computer)',
      'pip wheel --require-hashes --no-deps --no-build-isolation -r <this file>'
    ) + `${name}==${version} \\\n    --hash=sha256:${sdist.digests.sha256}\n`
  )
  console.log(
    `${main.length} libraries, ${build.length} build tools, insightface ${version} ${sdist.digests.sha256}`
  )
} finally {
  rmSync(work, { recursive: true, force: true })
}
